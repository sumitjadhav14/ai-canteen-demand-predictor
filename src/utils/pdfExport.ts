import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { SalesRecord } from '../types/canteen';

interface ExportPdfOptions {
  records: SalesRecord[];
  filterSummary: {
    foodItem: string;
    day: string;
    weather: string;
    holiday: string;
    event: string;
    search: string;
  };
  generatedBy?: string;
}

export function exportSalesRecordsToPdf({ records, filterSummary, generatedBy }: ExportPdfOptions): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // 1. Header Banner & Title
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 80, 'F');

  // Institution / System Wordmark
  doc.setTextColor(245, 158, 11); // amber-500
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('CANTEEN DEMAND & SALES MANAGEMENT SYSTEM', 40, 36);

  doc.setTextColor(226, 232, 240); // slate-200
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text('Administrative Canteen Operations & Food Inventory Audit Report', 40, 56);

  // Date and Generated By
  const todayStr = new Date().toLocaleDateString('en-US', {
    weekday: 'short',
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text(`Generated: ${todayStr}`, pageWidth - 40, 36, { align: 'right' });
  doc.text(`Supervisor: ${generatedBy || 'Canteen Operations Staff'}`, pageWidth - 40, 56, { align: 'right' });

  // 2. Report Overview & Filter Metadata Box
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(203, 213, 225); // slate-300
  doc.roundedRect(40, 95, pageWidth - 80, 58, 6, 6, 'FD');

  doc.setTextColor(30, 41, 59); // slate-800
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('ACTIVE FILTER PARAMETERS', 52, 112);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);

  const colA = `• Food Item: ${filterSummary.foodItem}    • Day: ${filterSummary.day}    • Weather: ${filterSummary.weather}`;
  const colB = `• Holiday: ${filterSummary.holiday}    • Special Event: ${filterSummary.event}    • Search Query: ${filterSummary.search || 'None'}`;
  doc.text(colA, 52, 128);
  doc.text(colB, 52, 142);

  // 3. Executive KPI Summary Cards
  const totalUnits = records.reduce((acc, curr) => acc + curr.Units_Sold, 0);
  const avgUnits = records.length ? (totalUnits / records.length).toFixed(1) : '0';
  const maxUnits = records.length ? Math.max(...records.map((r) => r.Units_Sold)) : 0;

  const cardY = 164;
  const cardWidth = (pageWidth - 80 - 30) / 4;
  const cardHeight = 44;

  const stats = [
    { label: 'RECORD COUNT', val: `${records.length} entries` },
    { label: 'TOTAL UNITS SOLD', val: `${totalUnits.toLocaleString()} units` },
    { label: 'AVERAGE PER ENTRY', val: `${avgUnits} units` },
    { label: 'PEAK SINGLE SALE', val: `${maxUnits} units` },
  ];

  stats.forEach((st, i) => {
    const x = 40 + i * (cardWidth + 10);
    doc.setFillColor(241, 245, 249);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(x, cardY, cardWidth, cardHeight, 4, 4, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(st.label, x + 8, cardY + 16);

    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text(st.val, x + 8, cardY + 34);
  });

  // 4. Formatted Table with autoTable
  const tableData = records.map((r, index) => [
    index + 1,
    r.Date,
    r.Day.substring(0, 3),
    r.Food_Item,
    r.Weather,
    r.Student_Attendance,
    r.Previous_Day_Sales,
    r.Is_Holiday,
    r.Is_Special_Event,
    r.Units_Sold,
  ]);

  autoTable(doc, {
    startY: 222,
    margin: { left: 40, right: 40, bottom: 90 },
    head: [['#', 'Date', 'Day', 'Food Item', 'Weather', 'Attendance', 'Prev Sales', 'Holiday', 'Event', 'Units Sold']],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontSize: 8.5,
      fontStyle: 'bold',
      halign: 'center',
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [30, 41, 59],
      cellPadding: 4,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { halign: 'center', cellWidth: 24 },
      1: { halign: 'center', cellWidth: 58 },
      2: { halign: 'center', cellWidth: 36 },
      3: { halign: 'left', fontStyle: 'bold' },
      4: { halign: 'center', cellWidth: 50 },
      5: { halign: 'right', cellWidth: 56 },
      6: { halign: 'right', cellWidth: 52 },
      7: { halign: 'center', cellWidth: 44 },
      8: { halign: 'center', cellWidth: 44 },
      9: { halign: 'right', fontStyle: 'bold', textColor: [180, 83, 9], cellWidth: 52 },
    },
    didDrawPage: (data) => {
      // Footer on every page
      const currentHeight = doc.internal.pageSize.getHeight();
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(
        'AI Canteen Demand Predictor · Official Administrative Report',
        40,
        currentHeight - 20
      );
      doc.text(
        `Page ${data.pageNumber}`,
        pageWidth - 40,
        currentHeight - 20,
        { align: 'right' }
      );
    },
  });

  // 5. Verification Sign-off Box at the end
  const finalY = (doc as any).lastAutoTable.finalY + 20;

  // Check if sign-off box fits on current page or need addPage
  let signY = finalY;
  if (signY + 70 > pageHeight - 40) {
    doc.addPage();
    signY = 40;
  }

  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(40, signY, pageWidth - 80, 60, 4, 4, 'FD');

  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text('ADMINISTRATIVE VERIFICATION & SIGN-OFF', 50, signY + 18);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('Prepared By: __________________________ (Canteen In-charge)', 50, signY + 44);
  doc.text('Approved By: __________________________ (Campus Administrator)', pageWidth / 2 + 10, signY + 44);

  // Save the generated PDF
  const filename = `Canteen_Sales_Report_${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(filename);
}
